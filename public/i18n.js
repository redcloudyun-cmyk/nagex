  function detectLocale() {
    const saved = localStorage.getItem(STORAGE_KEY);
    if (saved === 'ko' || saved === 'en') return saved;
    return 'en';
  }

  let currentLocale = detectLocale();

  const missingKeys = new Set();

  function t(key, fallback) {
    const value = (translations[currentLocale] && translations[currentLocale][key]) || (translations.en && translations.en[key]);
    if (value != null) return value;
    missingKeys.add(String(key));
    if (fallback != null) return String(fallback);
    return String(key);
  }

  function applyLocale() {
    document.documentElement.lang = currentLocale;
    document.title = t('page.title');

    document.querySelectorAll('[data-i18n]').forEach((el) => {
      el.textContent = t(el.getAttribute('data-i18n'));
    });
    document.querySelectorAll('[data-i18n-value]').forEach((el) => {
      el.value = t(el.getAttribute('data-i18n-value'));
    });
    document.querySelectorAll('[data-i18n-placeholder]').forEach((el) => {
      el.setAttribute('placeholder', t(el.getAttribute('data-i18n-placeholder')));
    });
    document.querySelectorAll('[data-i18n-title]').forEach((el) => {
      el.setAttribute('title', t(el.getAttribute('data-i18n-title')));
    });
    document.querySelectorAll('[data-i18n-aria-label]').forEach((el) => {
      el.setAttribute('aria-label', t(el.getAttribute('data-i18n-aria-label')));
    });

    document.querySelectorAll('[data-i18n-lang-toggle]').forEach((el) => {
      el.textContent = t('header.langToggle');
    });
  }

  function getLocale() {
    return currentLocale;
  }

  function setLocale(locale) {
    if (locale !== 'ko' && locale !== 'en') return;
    currentLocale = locale;
    localStorage.setItem(STORAGE_KEY, locale);
    applyLocale();
  }

  function toggleLocale() {
    setLocale(currentLocale === 'ko' ? 'en' : 'ko');
  }

  window.NAGEX_I18N = { t, getLocale, setLocale, toggleLocale, applyLocale, getMissingKeys: () => Array.from(missingKeys) };

  if (document.readyState === 'loading') {
    document.addEventListener('DOMContentLoaded', applyLocale);
  } else {
    applyLocale();
  }
