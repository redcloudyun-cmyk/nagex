// Real UI journey for slides: prompt -> deck created -> panel preview -> download .pptx -> (inspected in PowerPoint separately) -> Recent -> refresh persistence.
const { chromium } = require('F:/nxppt/node_modules/playwright');
const fs = require('fs');
const [,, COOKIE, PROMPT_FILE, OUT, TAG] = process.argv;
const prompt = fs.readFileSync(PROMPT_FILE, 'utf8').trim();
const log = (k, v) => console.log(k + ': ' + (typeof v === 'string' ? v : JSON.stringify(v)).slice(0, 900));
(async () => {
  const browser = await chromium.launch({ headless: true });
  const mk = async () => { const c = await browser.newContext({ viewport: { width: 1440, height: 900 }, acceptDownloads: true }); const [n, v] = COOKIE.split('='); await c.addCookies([{ name: n, value: v, domain: '127.0.0.1', path: '/' }]); return c; };
  const ctx = await mk(); const page = await ctx.newPage();
  const api = [];
  page.on('response', (r) => { const u = new URL(r.url()); if (/creations|artifacts|route-input/.test(u.pathname)) api.push(r.request().method() + ' ' + u.pathname.replace(/pres_[0-9a-f]{24}/, 'pres_*').replace(/art_[0-9a-f]{24}/, 'art_*') + ' ' + r.status()); });
  await page.goto('http://127.0.0.1:8191/', { waitUntil: 'domcontentloaded' });
  await page.waitForTimeout(2500);
  await page.fill('#main-surface-input', prompt);
  await page.click('#main-send');
  const t0 = Date.now();
  await page.waitForFunction(() => /Presentation created|Unavailable|Error/.test(document.body.innerText), null, { timeout: 180000 }).catch(() => {});
  await page.waitForTimeout(2500);
  log('1_ELAPSED_MS', Date.now() - t0);
  log('1_META', await page.evaluate(() => (document.getElementById('main-result-meta') || {}).textContent));
  log('1_TITLE', await page.evaluate(() => (document.getElementById('main-result-title') || {}).textContent));
  await page.screenshot({ path: `${OUT}/${TAG}_1_created.png` });
  const link = page.locator('.main-result-download');
  log('1_DOWNLOAD_LINK_COUNT', await link.count());
  const [dl] = await Promise.all([page.waitForEvent('download', { timeout: 20000 }), link.first().click()]);
  const file = `${OUT}/${TAG}.pptx`;
  await dl.saveAs(file);
  log('1_DOWNLOAD', { suggested: dl.suggestedFilename(), bytes: fs.statSync(file).size, file });
  await page.reload({ waitUntil: 'domcontentloaded' });
  await page.waitForTimeout(3000);
  await page.getByText(/^Recent$/).first().click().catch(() => {});
  await page.waitForTimeout(2500);
  const recent = (await page.evaluate(() => document.body.innerText)).replace(/\n+/g, ' | ');
  log('2_RECENT_HAS_PRESENTATION', /Presentation|발표/.test(recent) && recent.includes(String(await Promise.resolve('')) ) || /Presentation/.test(recent));
  log('2_RECENT_SNIPPET', recent.slice(recent.indexOf('Recent', 100), recent.indexOf('Recent', 100) + 300));
  const p2 = await (await mk()).newPage();
  await p2.goto('http://127.0.0.1:8191/', { waitUntil: 'domcontentloaded' });
  await p2.waitForTimeout(3000);
  await p2.getByText(/^Recent$/).first().click().catch(() => {});
  await p2.waitForTimeout(2500);
  log('3_NEW_CONTEXT_RECENT_HAS_PRESENTATION', /Presentation/.test(await p2.evaluate(() => document.body.innerText)));
  log('API_CALLS', api);
  await browser.close();
})();
